def set_seed(seed):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def rng_state():
    st = {
        "python": random.getstate(),
        "numpy": np.random.get_state(),
        "torch": torch.get_rng_state(),
    }
    if torch.cuda.is_available():
        st["cuda"] = torch.cuda.get_rng_state_all()
    return st


def load_rng_state(st):
    try:
        random.setstate(_tuplify(st["python"]))
        np.random.set_state(_np_state(st["numpy"]))
        torch.set_rng_state(_as_byte_tensor(st["torch"]))
        if torch.cuda.is_available() and "cuda" in st and st["cuda"] is not None:
            torch.cuda.set_rng_state_all([_as_byte_tensor(x) for x in st["cuda"]])
    except Exception as e:                       # a resumed RNG mismatch must not
        log(f"[warn] could not fully restore RNG state ({e!r}); continuing")


def _tuplify(x):
    if isinstance(x, list):
        return tuple(_tuplify(v) for v in x)
    return x


def _np_state(x):
    # np.random.get_state() -> ('MT19937', ndarray[uint32], pos, has_gauss, cached_gaussian)
    keys = list(x)
    keys[1] = np.asarray(keys[1], dtype=np.uint32)
    return tuple(keys)


def _as_byte_tensor(x):
    if isinstance(x, torch.Tensor):
        return x.to(torch.uint8).cpu()
    return torch.tensor(np.asarray(x, dtype=np.uint8), dtype=torch.uint8)
